// Local browser acceptance. Never prints credentials or uses a personal browser profile.
import {chromium} from '../app/node_modules/playwright-core/index.mjs';
import {readFile, mkdir} from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';

const directory=path.resolve(process.argv[2] || 'local-config/gateway-dev-20261104');
const password=(await readFile(path.join(directory,'admin-login.txt'),'utf8')).trim();
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
try {
  const page=await browser.newPage({viewport:{width:1440,height:1050}});
  const failures=[];page.on('pageerror',e=>failures.push(e.message));
  await page.goto('http://127.0.0.1:8787/admin');
  await page.locator('#password').fill(password);
  await page.locator('#login-form button').click();
  await page.locator('#console').waitFor({state:'visible'});
  console.log('browser_login: PASS');
  const suffix=Date.now().toString().slice(-7),user='验收用户-'+suffix,channel='验收通道-'+suffix;
  await page.locator('#user-name').fill(user);
  await page.locator('#user-form button').click();
  await page.locator('#user-list tr').filter({hasText:user}).waitFor();
  await page.locator('#channel-name').fill(channel);
  await page.locator('#channel-model').fill('browser-legal-'+suffix);
  await page.locator('#channel-form button').click();
  const channelRow=page.locator('#channel-list tr').filter({hasText:channel});
  await channelRow.getByRole('button',{name:'启用通道',exact:true}).click();
  await channelRow.getByRole('button',{name:'禁用通道',exact:true}).waitFor();
  await page.locator('#grant-user').selectOption({label:user});
  await page.locator('#grant-channel').selectOption({label:channel});
  await page.locator('#grant-form').getByRole('button',{name:'授予访问权限'}).click();
  await page.locator('#grant-list tr').filter({hasText:user}).waitFor();
  await page.locator('#issue-key').click();
  await page.locator('#key-result').waitFor({state:'visible'});
  const config=JSON.parse(await page.locator('#client-config').inputValue());
  assert.ok(config.api_key.startsWith('pgw_'));
  console.log('browser_user_channel_grant_issue: PASS');
  await page.locator('#probe-key').click();
  await page.waitForFunction(()=>document.getElementById('probe-result').textContent.startsWith('真实调用通过')||document.getElementById('probe-result').textContent.startsWith('已阻断'),null,{timeout:240000});
  const probe=await page.locator('#probe-result').textContent();
  assert.ok(probe.startsWith('真实调用通过'),probe);
  console.log('browser_real_model: PASS');
  await page.locator('#clear-key').click();
  await page.locator('#grant-list tr').filter({hasText:user}).getByRole('button',{name:'撤销授权'}).click();
  await page.locator('#grant-list tr').filter({hasText:user}).waitFor({state:'detached'});
  const revoked=await page.request.get('http://127.0.0.1:8787/v1/models',{headers:{Authorization:'Bearer '+config.api_key}});
  assert.equal(revoked.status(),401);
  console.log('browser_revoke_authorization: PASS');
  // Disable test resources; keep audit evidence and no usable browser test credential.
  await page.locator('#key-list tr').filter({hasText:user}).getByRole('button',{name:'撤销 Key'}).click();
  await page.locator('#user-list tr').filter({hasText:user}).getByRole('button',{name:'禁用用户'}).click();
  await channelRow.getByRole('button',{name:'禁用通道',exact:true}).click();
  await channelRow.getByRole('button',{name:'启用通道',exact:true}).waitFor();
  assert.equal(await page.locator('#client-config').inputValue(),'');
  await mkdir('test-results',{recursive:true});
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'test-results/gateway-admin.png',fullPage:true});
  assert.deepEqual(failures,[]);
  await page.locator('#logout').click();
  await page.locator('#login').waitFor({state:'visible'});
  console.log('browser_logout_no_console_errors: PASS');
} finally {await browser.close();}
